"""Pull requests for projects that opted in to GitHub verification (shared by the CLI and the engine).

Governance: an accepted task becomes a draft pull request (never a push to the base branch). Coding
Brain then asks before merging, and merges only when every check is green, the PR is mergeable and
its head is still the commit the user was asked about. Branch protection is never bypassed.
"""
from __future__ import annotations

from . import config as settings
from .. import remote_verify


def enabled(context) -> dict | None:
    return settings.verification_for(context.config, context.root)


def body(task: dict) -> str:
    evidence = task.get("test_evidence") or {}
    proposal = task.get("proposal") or {}
    files = "\n".join(f"- `{change.get('path')}`" for change in proposal.get("changes", [])[:50])
    completion = (task.get("completion") or {}).get("status", "unchecked")
    return (f"## Goal\n{task.get('goal', '')[:2000]}\n\n## Plan\n{str(proposal.get('plan', ''))[:4000]}\n\n"
            f"## Files\n{files or '-'}\n\n## Verification\n"
            f"- Tests: {'passed' if evidence.get('passed') else 'not passed'} ({evidence.get('profile', 'sandbox')})"
            + (f": {evidence['url']}" if evidence.get("url") else "") +
            f"\n- Requirement checks: {completion}\n- Accepted by the user in Coding Brain (task `{task['id'][:8]}`)\n\n"
            "Coding Brain asks before merging and merges only with every check green.\n\n"
            "Generated by Coding Brain.")


def publish(context, task: dict) -> dict | None:
    """Open a draft PR for an accepted task's branch. Returns the PR record, or None when off."""
    options = enabled(context)
    if not options or not task.get("branch") or not task.get("commit"):
        return None
    try:
        url = remote_verify.publish_pull_request(context.root, options, task["branch"], task["commit"],
                                                 f"Coding Brain: {task['goal'][:150]}", body(task))
        task["pull_request"] = {"url": url, "branch": task["branch"]}
    except (remote_verify.RemoteUnavailable, OSError) as error:
        task["pull_request"] = {"error": str(error)[:500], "branch": task["branch"]}
    return task["pull_request"]


def status(context, task: dict) -> dict:
    """The PR's checks, and whether Coding Brain may now ask to merge (ask_merge + the head to confirm)."""
    record = task.get("pull_request") or {}
    if not record.get("url"):
        raise ValueError("this task has no pull request")
    state = remote_verify.pull_request_checks(context.root, enabled(context) or {}, record["url"])
    return {**state, "url": record["url"], "ask_merge": state["green"],
            "question": (f"All {len(state['checks'])} checks are green on {record['url']}. Merge it?"
                         if state["green"] else None)}


def merge(context, task: dict, confirmed_head: str) -> str:
    record = task.get("pull_request") or {}
    if not record.get("url"):
        raise ValueError("this task has no pull request")
    url = remote_verify.merge_pull_request(context.root, enabled(context) or {}, record["url"], confirmed_head)
    record["merged"] = confirmed_head
    return url
